"""Расчёты шага «Исследование». Запуск: python3 calc/research.py из папки проекта.
Исходные числа — materials/показатели-подписки.xlsx (S-003) и записка (S-002)."""
import csv, pathlib
T = pathlib.Path(__file__).resolve().parent.parent / "materials" / "_text"
def rows(n): return list(csv.reader(open(T / f"показатели-подписки.xlsx.лист{n}.csv", encoding="utf-8")))[2:]
co = {r[0]: (int(r[1]), int(r[2])) for r in rows(1)}
q = lambda ms: tuple(sum(co[m][i] for m in ms) for i in (0, 1))
q1 = q(["2026-01", "2026-02", "2026-03"]); q3 = q(["2026-07", "2026-08", "2026-09"])
print("== В1. Прирост 1 кв. -> 3 кв.")
print("1 кв.: пробных", q1[0], "оплатили", q1[1], f"{100*q1[1]/q1[0]:.1f}%")
print("3 кв.: пробных", q3[0], "оплатили", q3[1], f"{100*q3[1]/q3[0]:.1f}%")
dt, dp = q3[0]-q1[0], q3[1]-q1[1]
print(f"Прирост пробных {dt} (+{100*dt/q1[0]:.0f}%), оплативших {dp} (+{100*dp/q1[1]:.0f}%), доля оплативших среди добавочных пробных {100*dp/dt:.1f}%")
print(f"Реклама 5.1 -> 9.2 млн: +{100*(9.2-5.1)/5.1:.0f}%; добавочный оплативший стоил {(9.2-5.1)*1e6/dp:.0f} ₽")
ch = {r[0]: (int(r[1]), int(r[2]), int(r[3])) for r in rows(2)}
free = [k for k in ch if k.startswith(("Поиск", "Рекоменд"))]
ft = sum(ch[k][0] for k in free); fp = sum(ch[k][1] for k in free)
print(f"Органика+рекомендации 3 кв.: {fp}/{ft} = {100*fp/ft:.1f}% (январь в целом 31.0%)")
paid = [k for k in ch if k not in free]
pt = sum(ch[k][0] for k in paid); pp = sum(ch[k][1] for k in paid); pc = sum(ch[k][2] for k in paid)
print(f"Платные каналы 3 кв.: {pp}/{pt} = {100*pp/pt:.1f}%, доля в пробных {100*pt/q3[0]:.1f}%, расходы {pc} тыс.")
print("Какой должна быть доля органики+рекомендаций среди пробных, чтобы при нынешних долях оплаты каналов получить 31%:")
rf, rp = fp/ft, pp/pt
print(f"  x = {(0.31-rp)/(rf-rp)*100:.0f}% (сейчас {100*ft/q3[0]:.0f}%)")
print("== В3. Верхние оценки: перевод 10% всех пробных (2310 чел.) между группами при нынешних долях оплаты групп")
b = [(int(r[1]), int(r[2])) for r in rows(3)]; rate = [p/t for t, p in b]; N = sum(t for t, _ in b); P = sum(p for _, p in b)
for name, a, z in [("не открыл -> прочитал четверть+", 0, 2), ("начал и бросил -> аудио 60+ мин", 1, 3), ("не открыл -> начал и бросил", 0, 1)]:
    g = 0.10*N*(rate[z]-rate[a]); print(f"  {name}: +{g:.0f} оплативших, доля {100*(P+g)/N:.1f}% (сейчас {100*P/N:.1f}%)")
print("== В5. Окупаемость: выручка с одного оплатившего после отчислений при допущениях")
price, m2, m3 = 349, 0.79, 0.71
cac = {k: 1000*c/p for k, (t, p, c) in ch.items() if c}
for r in (0.85, 0.90, 0.95):
    months = 1 + m2 + m3/(1-r) - m3 + m3  # 1-й, 2-й, затем 3-й и далее с удержанием r
    for share in (0.4, 0.55, 0.7):
        v = price*months*share
        ok = ", ".join(f"{k.split()[0]} {'да' if v >= c else 'нет'}" for k, c in cac.items())
        print(f"  удержание после 3-го мес. {r:.2f}, остаётся {share:.0%}: {months:.1f} мес., {v:.0f} ₽ | окупает: {ok}")
print("  Стоимость привлечения:", {k: round(c) for k, c in cac.items()})
print(f"  Сверка: 31000 платящих / ~{q3[1]/3:.0f} новых оплативших в мес. = {31000/(q3[1]/3):.0f} мес. при неизменном притоке")
print("== Купонный канал: что даёт отказ")
t, p, c = ch["Купонные сайты и промокоды"]
print(f"  расходы {c} тыс./кв., оплативших {p} ({100*p/q3[1]:.0f}% всех оплативших), доля без канала {100*(q3[1]-p)/(q3[0]-t):.1f}%")
t2, p2, c2 = ch["Партнёрская рассылка оператора связи"]
print(f"  без купонных и оператора: {100*(q3[1]-p-p2)/(q3[0]-t-t2):.1f}%, оплативших {q3[1]-p-p2}, высвобождается {c+c2} тыс./кв.")
