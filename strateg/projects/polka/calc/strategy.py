"""Расчёты шага «Стратегии». Запуск: python3 calc/strategy.py.
Исходные числа — S-003, лист «Каналы», 3 кв. 2026 (E-021, E-022); допущения названы в строках."""
from math import sqrt
WEEKS_Q = 13
# канал: (пробных за 3 кв., доля оплативших, расходы за квартал в тыс. руб.)
ch = {"органика": (5200, 0.33, 0), "рекомендации": (1900, 0.37, 380), "соцсети": (6800, 0.21, 4100)}
cut = {"купонные": (7300, 0.11, 3650), "оператор": (1900, 0.158, 1070)}

def tot(d):
    t = sum(v[0] for v in d.values()); p = sum(v[0]*v[1] for v in d.values()); c = sum(v[2] for v in d.values())
    return t, p, c

print("== Экономика привлечения до и после отказа от двух каналов (уровень 3 кв.)")
t_all, p_all, c_all = tot({**ch, **cut})
t, p, c = tot(ch)
print(f"сейчас: пробных {t_all}, оплативших {p_all:.0f}, расходы каналов {c_all/1000:.2f} млн, на одного оплатившего {c_all*1000/p_all:.0f} руб.")
print(f"после:  пробных {t}, оплативших {p:.0f}, доля {100*p/t:.1f}%, расходы {c/1000:.2f} млн, на одного оплатившего {c*1000/p:.0f} руб.")
print(f"темп сейчас: оплативших в месяц {p_all/3:.0f}")
print(f"темп после отказа: оплативших в месяц {p/3:.0f}, пробных в неделю {t/WEEKS_Q:.0f}")

print("== Размер опыта: 4 группы поровну, набор N недель, оплата видна через 7 дней после набора")
def mde(p0, n):  # наименьшая разница, которую опыт отличает от случайной: уровень 5% двусторонний, мощность 80%
    return (1.96+0.84)*sqrt(2*p0*(1-p0)/n)
for name, keys in (("органика+рекомендации", ("органика", "рекомендации")), ("органика+рекомендации+соцсети", tuple(ch))):
    sub = {k: ch[k] for k in keys}
    tt, pp, _ = tot(sub); p0 = pp/tt
    for weeks in (4, 6):
        n = tt/WEEKS_Q*weeks/4
        print(f"{name}, набор {weeks} нед.: в группе {n:.0f} пробных, исходная доля {100*p0:.1f}%, различимая разница {100*mde(p0, n):.1f} п.п.")

print("== Порог ценовой группы: выручка с одного пробного не ниже нынешней")
tt, pp, _ = tot(ch); p0 = pp/tt
for new in (299,):
    print(f"цена {new}: доля оплативших должна быть не ниже {100*p0*349/new:.1f}% при {100*p0:.1f}% в контрольной группе (в {349/new:.2f} раза, +{100*p0*(349/new-1):.1f} п.п.)")

print("== Порог для первой недели: что нужно, чтобы выйти на 31% по трём каналам")
print(f"нужно +{100*(0.31-p0):.1f} п.п. к {100*p0:.1f}%")
