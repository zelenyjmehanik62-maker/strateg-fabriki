# Расчёты для findings/options. Запуск: python3 calc/calc.py (из папки проекта)
import csv
T='materials/_text/показатели-подписки.xlsx.'
def rows(n): return list(csv.reader(open(T+f'лист{n}.csv',encoding='utf-8')))
print('== Когорты: удержание 2-го и 3-го месяца от оплативших 1-й')
for r in rows(1)[2:]:
    m,s,p1,sh,p2,p3=r[0],int(r[1]),int(r[2]),r[3],r[4],r[5]
    print(m, f'конв {p1/s*100:.1f}%', f'м2/м1 {int(p2)/p1*100:.1f}%', f'м3/м1 {int(p3)/p1*100:.1f}%' if p3 else 'м3 нет')
print('== Каналы 3 кв.')
tot=[0,0,0]
for r in rows(2)[2:]:
    s,p,c=int(r[1]),int(r[2]),int(r[3]); tot=[tot[0]+s,tot[1]+p,tot[2]+c]
    print(r[0], f'конв {p/s*100:.1f}%', f'доля стартов {s:5d}', f'руб/оплатившего {c*1000/p:,.0f}' if c else 'руб/оплатившего 0')
print('итого', tot, f'конв {tot[1]/tot[0]*100:.1f}%', f'руб/оплатившего {tot[2]*1000/tot[1]:,.0f}')
nocoup=[tot[0]-7300, tot[1]-803]; print('без купонов: конв', f'{nocoup[1]/nocoup[0]*100:.1f}%')
print('доля купонов в стартах', f'{7300/tot[0]*100:.1f}%', 'в расходах', f'{3650/tot[2]*100:.1f}%', 'в оплативших', f'{803/tot[1]*100:.1f}%')
print('== Пробный период 3 кв.')
g=rows(3)[2:]; S=sum(int(r[1]) for r in g); P=sum(int(r[2]) for r in g)
for r in g: print(r[0][:45], f'доля {int(r[1])/S*100:.1f}%', f'конв {int(r[2])/int(r[1])*100:.1f}%')
print('всего',S,P,f'{P/S*100:.1f}%')
print('== Причины отмены')
g=rows(4)[2:]; N=sum(int(r[1]) for r in g)
for r in g: print(r[0], f'{int(r[1])/N*100:.1f}%')
print('ответили', N)
print('== Экономика (оценки)')
price=349; r2=0.79; r3=0.705
rev3=price*(1+r2+r3); print(f'выручка с оплатившего за 3 мес ≈ {rev3:.0f} ₽')
for ch,c in [('купоны',4545),('соцсети',2871),('оператор',3567),('друзья',541)]:
    print(ch, f'затраты/выручка 3 мес = {c/rev3:.1f}')
print(f'валовая выручка в месяц, 31 тыс. × 349 ₽ ≈ {31000*price/1e6:.1f} млн ₽')
print('== Сценарии конверсии (иллюстрация, прогноз)')
starts=23100-7300; paid=4950-803
print(f'без купонов: {paid/starts*100:.1f}%')
# сдвиг 10% стартов из "не открыл" в "прочитал четверть+" (38%) — эффект активации
base=0.262
for shift in (0.05,0.10):
    print(f'+ сдвиг {shift*100:.0f}% стартов из «не открыл» (3,1%) в «четверть+» (38%): {(base+shift*(0.38-0.031))*100:.1f}%')
    print(f'+ сдвиг {shift*100:.0f}% стартов из «не открыл» в «аудио 60+» (61%): {(base+shift*(0.61-0.031))*100:.1f}%')
print('тренд: падение 31→22 за 8 мес =', f'{(31-22)/8:.2f} п.п./мес')
print('== Цена: снижение до 299 ₽ для всех')
loss=(349-299)*31000; print(f'потеря выручки ≈ {loss/1e6:.2f} млн ₽ в месяц; чтобы компенсировать, нужно +{loss/299:.0f} подписчиков ({loss/299/31000*100:.1f}%)')
