# Объём операций без согласия за 2025 год, восстановленный из доли возврата (S-006)
returned_mln = 1731.3   # млн руб., возвращено
share = 0.059           # 5,9% от всего объёма
total_bln = returned_mln / share / 1000
print(f"Возвращено 1731,3 млн руб. = 5,9% объёма -> весь объём ≈ {total_bln:.1f} млрд руб. за 2025 год (округление доли даёт погрешность ±1 млрд)")
