# Прогноз выручки подписки на каждые 100 000 семей-абонентов, которым её покажут.
# Допущения (все — гипотезы): цена 249 руб./мес как у МТС и МегаФона (E-022, E-023);
# доля подключивших и оставшихся платить: 1%, 3%, 5%; без учёта пробного периода, НДС и затрат.
price = 249
families = 100_000
for share in (0.01, 0.03, 0.05):
    payers = families * share
    month = payers * price
    print(f"доля {share:.0%}: платящих {payers:,.0f}; выручка {month/1e6:.2f} млн руб. в месяц; {month*12/1e6:.1f} млн руб. за 12 месяцев".replace(",", " "))
